-- 1. TABLA DE PERFILES
-- Guarda el nombre y el rol de los usuarios registrados.

CREATE TABLE public.perfiles (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'encargado',
    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT rol_permitido
        CHECK (rol IN ('administrador', 'encargado'))
);

-- 2. TABLA DE MATERIALES
-- Almacena los materiales y sus cantidades disponibles.

CREATE TABLE public.materiales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    nombre TEXT NOT NULL,
    descripcion TEXT,
    cantidad INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 0,
    unidad_medida TEXT NOT NULL,
    codigo TEXT,
    categoria TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT cantidad_no_negativa
        CHECK (cantidad >= 0),

    CONSTRAINT stock_minimo_no_negativo
        CHECK (stock_minimo >= 0)
);

-- 3. TABLA DE MOVIMIENTOS
-- Registra las entradas y salidas del inventario.

CREATE TABLE public.movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    material_id BIGINT NOT NULL,
    tipo TEXT NOT NULL,
    cantidad INTEGER NOT NULL,
    observacion TEXT,

    CONSTRAINT movimientos_material_id_fkey
        FOREIGN KEY (material_id)
        REFERENCES public.materiales(id),

    CONSTRAINT cantidad_movimiento_positiva
        CHECK (cantidad > 0),

    CONSTRAINT tipo_movimiento_valido
        CHECK (tipo IN ('entrada', 'salida'))
);

